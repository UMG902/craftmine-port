    private static volatile Map<Item, Float> fallback;

    private static Map<Item, Float> fallback() {
        Map<Item, Float> map = fallback;
        if (map == null) {
            synchronized (CraftmineExchangeValues.class) {
                map = fallback;
                if (map == null) {
                    map = new HashMap<>();
                    int skipped = 0;
                    for (String entry : TABLE) {
                        int eq = entry.indexOf('=');
                        Identifier id = Identifier.withDefaultNamespace(entry.substring(0, eq));
                        Item item = BuiltInRegistries.ITEM.getOptional(id).orElse(null);
                        if (item != null) {
                            map.put(item, Float.parseFloat(entry.substring(eq + 1)));
                        } else {
                            skipped++;
                        }
                    }
                    fallback = map;
                    // Task 59: production evidence that the table resolved
                    com.mojang.logging.LogUtils.getLogger().info(
                        "[craftmine] exchange values: {} items priced, {} table entries skipped (not in this registry)",
                        map.size(), skipped);
                }
            }
        }
        return map;
    }

    /** True when the item has a table value (tooltip gating for component-less stacks). */
    public static boolean hasFallback(Item item) {
        return fallback().containsKey(item);
    }

    /**
     * The stack's exchange value: explicit component first (also covers
     * PlayerUnlock's on-stack zeroing), then the merged table, then none.
     */
    public static ItemExchangeValue forStack(ItemStack stack) {
        ItemExchangeValue component = stack.get(CraftmineDataComponents.EXCHANGE_VALUE);
        if (component != null) {
            return component;
        }
        Float value = fallback().get(stack.getItem());
        return value == null ? ItemExchangeValue.NO_EXCHANGE : new ItemExchangeValue(value);
    }
