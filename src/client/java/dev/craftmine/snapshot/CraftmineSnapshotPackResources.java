package dev.craftmine.snapshot;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.Base64;
import java.util.Enumeration;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

import net.minecraft.resources.Identifier;
import net.minecraft.server.packs.AbstractPackMetadataResources;
import net.minecraft.server.packs.PackLocationInfo;
import net.minecraft.server.packs.PackResources;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.resources.IoSupplier;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Serves only the explicitly approved 25w14craftmine assets from the user's
 * installed snapshot. The allowlist is a checked-in client resource; an
 * unlisted path is never exposed, even if it exists in the snapshot archive.
 *
 * <p>Task 32 (2026-11-01): adopted from the maintainer's asset patch package
 * and re-verified against ground truth. All 184 removed mod-shipped assets
 * are byte-identical (git-blob SHA) to the snapshot's same-path entries, and
 * every allowlisted path exists in the snapshot; the only allowlisted path
 * that also exists in 26.3 is the CRAFTMINE title logo - the one intentional
 * same-path replacement. One entry was added beyond the patch on adoption:
 * {@code textures/gui/title/minecraft.png.mcmeta} (26.3 ships no logo
 * .mcmeta; the snapshot's carries the blur flag for the animated logo).
 *
 * <p>Server data is intentionally not served from the old snapshot format.
 * Synthetic resources generated by this mod (currently the menu background)
 * remain independent of the snapshot allowlist.
 */
public final class CraftmineSnapshotPackResources extends AbstractPackMetadataResources implements PackResources {
    private static final Logger LOGGER = LoggerFactory.getLogger("craftmine/snapshot");
    private static final String ALLOWLIST_RESOURCE = "craftmine-snapshot-assets.txt";

    /**
     * A 26.3 menu texture generated by the port because the 25w14 snapshot
     * predates the current menu-background resource. It is intentionally not
     * sourced from the installed snapshot.
     */
    private static final Map<String, IoSupplier<InputStream>> SYNTHETIC_ASSETS = Map.of(
            "assets/minecraft/textures/gui/menu_background.png",
            () -> new ByteArrayInputStream(Base64.getDecoder().decode(
                    "iVBORw0KGgoAAAANSUhEUgAAABAAAAAQCAQAAAC1+jfqAAAAEUlEQVR42mNg6CEARxWMJAUAJICMAeBZGPQAAAAASUVORK5CYII=")));

    private final Path snapshotJar;
    private final Set<String> allowedPaths;
    private volatile ZipFile zip;

    public CraftmineSnapshotPackResources(PackLocationInfo info, Path snapshotJar, Set<String> allowedPaths) {
        super(info);
        this.snapshotJar = snapshotJar;
        this.allowedPaths = allowedPaths;
    }

    /**
     * Loads the checked-in path allowlist. Invalid entries are ignored and a
     * missing/unreadable list fails closed, rather than exposing the archive.
     */
    public static Set<String> snapshotAssetAllowlist() {
        try (InputStream input = CraftmineSnapshotPackResources.class.getClassLoader()
                .getResourceAsStream(ALLOWLIST_RESOURCE)) {
            if (input == null) {
                LOGGER.error("Craftmine: {} is missing; snapshot asset pack will serve no archive assets",
                        ALLOWLIST_RESOURCE);
                return Set.of();
            }

            String content = new String(input.readAllBytes(), StandardCharsets.UTF_8);
            Set<String> paths = new TreeSet<>();
            for (String rawLine : content.lines().toList()) {
                String path = rawLine.trim();
                if (path.isEmpty() || path.startsWith("#")) {
                    continue;
                }
                if (!path.startsWith("assets/") || path.endsWith("/")
                        || path.contains("\\") || path.contains("..")) {
                    LOGGER.warn("Craftmine: ignoring invalid snapshot allowlist entry: {}", path);
                    continue;
                }
                paths.add(path);
            }
            LOGGER.info("Craftmine: loaded {} approved snapshot asset paths", paths.size());
            return Set.copyOf(paths);
        } catch (IOException e) {
            LOGGER.error("Craftmine: failed to read {}; snapshot asset pack will serve no archive assets",
                    ALLOWLIST_RESOURCE, e);
            return Set.of();
        }
    }

    private ZipFile zip() throws IOException {
        ZipFile local = this.zip;
        if (local == null) {
            synchronized (this) {
                local = this.zip;
                if (local == null) {
                    local = new ZipFile(this.snapshotJar.toFile());
                    this.zip = local;
                }
            }
        }
        return local;
    }

    @Override
    public IoSupplier<InputStream> getRootResource(String... names) {
        return resource(String.join("/", names));
    }

    @Override
    public IoSupplier<InputStream> getResource(PackType type, Identifier id) {
        if (type == PackType.SERVER_DATA) {
            return null;
        }
        return resource("assets/" + id.getNamespace() + "/" + id.getPath());
    }

    @Override
    public void listResources(PackType type, String namespace, String path, ResourceOutput output) {
        if (type == PackType.SERVER_DATA) {
            return;
        }

        String namespacePrefix = "assets/" + namespace + "/";
        String prefix = namespacePrefix + (path.isEmpty() ? "" : path.endsWith("/") ? path : path + "/");
        try {
            ZipFile local = zip();
            synchronized (local) {
                Enumeration<? extends ZipEntry> entries = local.entries();
                while (entries.hasMoreElements()) {
                    ZipEntry entry = entries.nextElement();
                    if (entry.isDirectory()) {
                        continue;
                    }
                    String name = entry.getName();
                    if (!name.startsWith(prefix) || !this.allowedPaths.contains(name)
                            || SYNTHETIC_ASSETS.containsKey(name)) {
                        continue;
                    }
                    String relative = name.substring(namespacePrefix.length());
                    output.accept(Identifier.fromNamespaceAndPath(namespace, relative),
                            () -> local.getInputStream(entry));
                }
            }

            // Synthetic assets are owned by the port, not by the snapshot;
            // always make them discoverable even though they are not allowlisted.
            for (Map.Entry<String, IoSupplier<InputStream>> synthetic : SYNTHETIC_ASSETS.entrySet()) {
                String name = synthetic.getKey();
                if (name.startsWith(prefix)) {
                    String relative = name.substring(namespacePrefix.length());
                    output.accept(Identifier.fromNamespaceAndPath(namespace, relative), synthetic.getValue());
                }
            }
        } catch (IOException e) {
            LOGGER.warn("Craftmine: failed to list approved snapshot resources under {} ({})", prefix,
                    this.snapshotJar, e);
        }
    }

    @Override
    public Set<String> getNamespaces(PackType type) {
        if (type == PackType.SERVER_DATA) {
            return Set.of();
        }
        Set<String> namespaces = new HashSet<>();
        addNamespaces(namespaces, this.allowedPaths);
        addNamespaces(namespaces, SYNTHETIC_ASSETS.keySet());
        return Set.copyOf(namespaces);
    }

    private static void addNamespaces(Set<String> namespaces, Iterable<String> paths) {
        for (String name : paths) {
            if (!name.startsWith("assets/")) {
                continue;
            }
            int end = name.indexOf('/', "assets/".length());
            if (end > "assets/".length()) {
                namespaces.add(name.substring("assets/".length(), end));
            }
        }
    }

    @Override
    public void close() {
        ZipFile local = this.zip;
        this.zip = null;
        if (local != null) {
            try {
                local.close();
            } catch (IOException e) {
                LOGGER.debug("Craftmine: error closing snapshot jar {}", this.snapshotJar, e);
            }
        }
    }

    private IoSupplier<InputStream> resource(String path) {
        // The port-owned synthetic resource takes precedence over any archive entry.
        IoSupplier<InputStream> synthetic = SYNTHETIC_ASSETS.get(path);
        if (synthetic != null) {
            return synthetic;
        }
        if (!this.allowedPaths.contains(path)) {
            return null;
        }
        try {
            ZipFile local = zip();
            synchronized (local) {
                ZipEntry entry = local.getEntry(path);
                if (entry == null || entry.isDirectory()) {
                    return null;
                }
                return () -> local.getInputStream(entry);
            }
        } catch (IOException e) {
            LOGGER.warn("Craftmine: failed to read approved asset {} from snapshot pack ({})", path,
                    this.snapshotJar, e);
            return null;
        }
    }
}
