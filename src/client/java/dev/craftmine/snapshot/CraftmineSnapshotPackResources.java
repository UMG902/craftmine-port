package dev.craftmine.snapshot;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Base64;
import java.util.Enumeration;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.function.Predicate;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

import net.minecraft.resources.Identifier;
import net.minecraft.server.packs.AbstractPackMetadataResources;
import net.minecraft.server.packs.PackLocationInfo;
import net.minecraft.server.packs.PackResources;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.resources.IoSupplier;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import java.util.stream.Stream;

/**
 * A {@link PackResources} that serves game assets straight out of the
 * user's officially installed 25w14craftmine snapshot jar - nothing is
 * copied, extracted or re-hosted.
 *
 * <p>Every lookup first consults a blocklist of paths that this mod itself
 * ships (the 26.3-format-migrated asset definitions in our jar). Those paths
 * return {@code null} here so the mod's own always-on resources win without
 * any dependency on resource-pack stack ordering; the snapshot pack only
 * fills in everything we deliberately do not carry (the CRAFTMINE title
 * logo, snapshot splashes, snapshot sound files, ...).
 *
 * <p>Data-pack lookups are refused outright: the snapshot's {@code data/}
 * folder is pre-26.3 format and must never reach the server side.
 */
public final class CraftmineSnapshotPackResources extends AbstractPackMetadataResources implements PackResources {
    private static final Logger LOGGER = LoggerFactory.getLogger("craftmine/snapshot");

    /**
     * Snapshot-provided definition categories that 26.3 parses with its own
     * (rewritten) formats and CANNOT consume in the snapshot's pre-26.3 form.
     * Serving them fails the initial resource reload: the post_effect/item
     * model/shader parsers throw (user log 2026-10-30: "Failed to parse post
     * chain ... Not a JSON object", "Couldn't parse item model 'black_bed'"),
     * the load-finished gate never opens, and 26.3 drops into resource-pack
     * recovery (title screen without gameLoadFinished - which also keeps the
     * panorama/screen extraction disabled). The mod ports these definitions
     * itself in 26.3 format; the pack only serves the content the mod does
     * not carry: textures, sounds, texts.
     */
    private static final List<String> INCOMPATIBLE_PREFIXES = List.of(
            "assets/minecraft/post_effect/",
            "assets/minecraft/items/",
            "assets/minecraft/shaders/",
            "assets/minecraft/particles/",
            "assets/minecraft/atlases/");

    /**
     * 26.3 textures the snapshot never shipped, regenerated by this mod so
     * the snapshot's LOOK survives on 26.3's rewritten menu system.
     *
     * <p>{@code textures/gui/menu_background.png}: vanilla 26.3 draws this
     * 16x16 grayscale-alpha tile over the (blurred) panorama on every
     * out-of-world screen. Vanilla's tile is black at 25% alpha, tuned for
     * its bright world panorama; under the code rain it leaves the backdrop
     * far too bright. The real snapshot dims its menu rain to roughly a
     * tenth of title brightness (measured off user screenshots 2026-10-30:
     * title peak green ~255, Select World peak ~27, p99 ~18), so we serve a
     * black tile at 140/255 (~55% transmitted) - calibrated on the headless
     * rig against the snapshot's Select World backdrop: 87% alpha measured
     * 3.5-4x too dark (p99 5 vs the snapshot's 18), 55% lands on it. The
     * in-world variant is left untouched (pause menus keep vanilla's
     * translucent world blur).
     */
    private static final Map<String, IoSupplier<InputStream>> SYNTHETIC_ASSETS = Map.of(
            "assets/minecraft/textures/gui/menu_background.png",
            () -> new java.io.ByteArrayInputStream(Base64.getDecoder().decode(
                    "iVBORw0KGgoAAAANSUhEUgAAABAAAAAQCAQAAAC1+jfqAAAAEUlEQVR42mNg6CEARxWMJAUAJICMAeBZGPQAAAAASUVORK5CYII=")));

    private final Path snapshotJar;
    private final Predicate<String> blockedPaths;
    private volatile ZipFile zip;

    public CraftmineSnapshotPackResources(PackLocationInfo info, Path snapshotJar, Predicate<String> blockedPaths) {
        super(info);
        this.snapshotJar = snapshotJar;
        this.blockedPaths = blockedPaths;
    }

    private static boolean incompatible(String path) {
        for (String prefix : INCOMPATIBLE_PREFIXES) {
            if (path.startsWith(prefix)) {
                return true;
            }
        }
        return false;
    }

    private ZipFile zip() throws IOException {
        ZipFile local = this.zip;
        if (local == null) {
            synchronized (this) {
                local = this.zip;
                if (local == null) {
                    local = new ZipFile(this.snapshotJar.toFile());
                    this.zip = local;
                }
            }
        }
        return local;
    }

    @Override
    public IoSupplier<InputStream> getRootResource(String... names) {
        return resource(String.join("/", names));
    }

    @Override
    public IoSupplier<InputStream> getResource(PackType type, Identifier id) {
        if (type == PackType.SERVER_DATA) {
            return null;
        }
        return resource("assets/" + id.getNamespace() + "/" + id.getPath());
    }

    @Override
    public void listResources(PackType type, String namespace, String path, ResourceOutput output) {
        if (type == PackType.SERVER_DATA) {
            return;
        }
        String namespacePrefix = "assets/" + namespace + "/";
        String prefix = namespacePrefix + (path.isEmpty() ? "" : path.endsWith("/") ? path : path + "/");
        try {
            ZipFile local = zip();
            synchronized (local) {
                Enumeration<? extends ZipEntry> entries = local.entries();
                while (entries.hasMoreElements()) {
                    ZipEntry entry = entries.nextElement();
                    if (entry.isDirectory()) {
                        continue;
                    }
                    String name = entry.getName();
                    if (!name.startsWith(prefix) || this.blockedPaths.test(name) || incompatible(name)) {
                        continue;
                    }
                    String relative = name.substring(namespacePrefix.length());
                    output.accept(Identifier.fromNamespaceAndPath(namespace, relative), () -> local.getInputStream(entry));
                }
            }
            for (Map.Entry<String, IoSupplier<InputStream>> synthetic : SYNTHETIC_ASSETS.entrySet()) {
                String name = synthetic.getKey();
                if (name.startsWith(prefix) && !this.blockedPaths.test(name) && !incompatible(name)) {
                    String relative = name.substring(namespacePrefix.length());
                    output.accept(Identifier.fromNamespaceAndPath(namespace, relative), synthetic.getValue());
                }
            }
        } catch (IOException e) {
            LOGGER.warn("Craftmine: failed to list snapshot pack resources under {} ({})", prefix, this.snapshotJar, e);
        }
    }

    @Override
    public Set<String> getNamespaces(PackType type) {
        if (type == PackType.SERVER_DATA) {
            return Set.of();
        }
        Set<String> namespaces = new HashSet<>();
        try {
            ZipFile local = zip();
            synchronized (local) {
                Enumeration<? extends ZipEntry> entries = local.entries();
                while (entries.hasMoreElements()) {
                    String name = entries.nextElement().getName();
                    if (name.startsWith("assets/")) {
                        int end = name.indexOf('/', "assets/".length());
                        if (end > 0) {
                            namespaces.add(name.substring("assets/".length(), end));
                        }
                    }
                }
            }
        } catch (IOException e) {
            LOGGER.warn("Craftmine: failed to enumerate snapshot pack namespaces ({})", this.snapshotJar, e);
        }
        return namespaces;
    }

    @Override
    public void close() {
        ZipFile local = this.zip;
        this.zip = null;
        if (local != null) {
            try {
                local.close();
            } catch (IOException e) {
                LOGGER.debug("Craftmine: error closing snapshot jar {}", this.snapshotJar, e);
            }
        }
    }

    private IoSupplier<InputStream> resource(String path) {
        if (this.blockedPaths.test(path) || incompatible(path)) {
            return null;
        }
        IoSupplier<InputStream> synthetic = SYNTHETIC_ASSETS.get(path);
        if (synthetic != null) {
            return synthetic;
        }
        try {
            ZipFile local = zip();
            synchronized (local) {
                ZipEntry entry = local.getEntry(path);
                if (entry == null || entry.isDirectory()) {
                    return null;
                }
                return () -> local.getInputStream(entry);
            }
        } catch (IOException e) {
            LOGGER.warn("Craftmine: failed to read {} from snapshot pack ({})", path, this.snapshotJar, e);
            return null;
        }
    }

    /**
     * Builds the blocklist from the paths this mod itself ships under
     * {@code assets/} in its own container (jar or exploded dev classes), so
     * our 26.3-format files always shadow the snapshot's originals.
     */
    public static Predicate<String> modShippedAssetPaths() {
        Set<String> shipped = new HashSet<>();
        try {
            for (Path root : net.fabricmc.loader.api.FabricLoader.getInstance()
                    .getModContainer("craftmine").orElseThrow().getRootPaths()) {
                Path assets = root.resolve("assets");
                if (!Files.isDirectory(assets)) {
                    continue;
                }
                try (Stream<Path> stream = Files.walk(assets)) {
                    stream.filter(Files::isRegularFile).forEach(file ->
                            shipped.add(root.relativize(file).toString().replace('\\', '/')));
                }
            }
        } catch (Exception e) {
            LOGGER.warn("Craftmine: could not build snapshot override blocklist; "
                    + "the snapshot pack will serve all of its assets", e);
        }
        return Set.copyOf(shipped)::contains;
    }
}
